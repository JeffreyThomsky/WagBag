SB.Locales = { ruRU=RU, enUS=EN, enGB=EN, deDE=DE, frFR=FR, esES=ES, esMX=ES, itIT=IT, ptBR=PT, koKR=KO, zhCN=ZHCN, zhTW=ZHTW }
SB.clientLocale = (GetLocale and GetLocale()) or "enUS"

function SB:SetLocale(locale)
    local selected = locale or self.localeOverride or self.clientLocale
    if selected == "enGB" then
        self.localeCode = "enGB"
        self.L = EN
    elseif self.Locales[selected] then
        self.localeCode = selected
        self.L = self.Locales[selected]
    else
        self.localeCode = "enUS"
        self.L = EN
    end
end

function SB:T(key, ...)
    local value = (self.L and self.L[key]) or EN[key] or RU[key] or key
    if select("#", ...) > 0 then return string.format(value, ...) end
    return value
end

